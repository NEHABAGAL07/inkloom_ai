"""
Marketing Copilot Schemas
Pydantic contracts for campaign brief inputs, brand-aware generation outputs,
draft persistence, and versioning.
"""
from datetime import datetime, timezone
from enum import Enum
from typing import List, Optional, Dict, Any
from pydantic import BaseModel, Field, ConfigDict


class MarketingContentType(str, Enum):
    CAPTION = "caption"
    HEADLINE = "headline"
    PUNCHLINE = "punchline"
    SLOGAN = "slogan"
    CTA = "cta"
    PRODUCT_DESCRIPTION = "product_description"
    CAMPAIGN_CONCEPT = "campaign_concept"
    AUDIENCE_VARIATION = "audience_variation"
    SHORT_COPY = "short_copy"
    LONG_COPY = "long_copy"
    REWRITE = "rewrite"
    COPY_IMPROVEMENT = "copy_improvement"


class MarketingChannel(str, Enum):
    INSTAGRAM = "instagram"
    LINKEDIN = "linkedin"
    WEBSITE = "website"
    EMAIL = "email"
    AD = "ad"
    PRINT = "print"
    GENERAL = "general"


class DesiredLength(str, Enum):
    SHORT = "short"
    MEDIUM = "medium"
    LONG = "long"


class CampaignBriefRequest(BaseModel):
    """
    Flexible campaign brief. No single field is strictly mandatory if
    partial information can produce a useful, brand-guided output.
    """
    product: Optional[str] = Field(None, description="Product or service name/description")
    campaign_objective: Optional[str] = Field(None, description="Primary campaign goal (e.g. Awareness, Conversion, Engagement)")
    target_audience: Optional[str] = Field(None, description="Target demographic, persona, or professional segment")
    channel: MarketingChannel = Field(default=MarketingChannel.GENERAL, description="Destination marketing channel")
    preferred_tone: Optional[str] = Field(None, description="Desired brand tone (e.g. Professional, Bold, Warm, Informative)")
    desired_length: DesiredLength = Field(default=DesiredLength.MEDIUM, description="Target length of the copy")
    call_to_action: Optional[str] = Field(None, description="Specific CTA desired")
    context_constraints: Optional[str] = Field(None, description="Campaign context, negative constraints, or special instructions")
    supporting_references: Optional[str] = Field(None, description="User-supplied references, stats, or notes")
    content_type: MarketingContentType = Field(default=MarketingContentType.SHORT_COPY, description="Type of copy requested")
    existing_content: Optional[str] = Field(None, description="Source copy when requesting rewrites or improvements")
    num_alternatives: int = Field(default=3, ge=1, le=5, description="Number of creative alternatives to generate")

    model_config = ConfigDict(extra="ignore")


class MarketingAlternative(BaseModel):
    """
    Structured creative alternative generated by the Marketing Copilot.
    Clearly distinguishes AI-generated suggestions from audited/approved assets.
    """
    id: str = Field(description="Unique identifier for the generated alternative")
    content_type: str = Field(description="Format of the copy")
    text: str = Field(description="Generated copy draft")
    creative_rationale: str = Field(description="Explanation of the creative approach, angle, and psychological appeal")
    target_channel: str = Field(description="Intended marketing channel")
    target_audience: str = Field(description="Intended target audience persona")
    brand_tone_alignment: str = Field(description="How this alternative adheres to approved brand tone guidelines")
    assumptions: List[str] = Field(default_factory=list, description="Explicit assumptions or conservative defaults applied")
    missing_facts: List[str] = Field(default_factory=list, description="Product facts or certifications that were unverified in knowledge base")
    compliance_warnings: List[str] = Field(default_factory=list, description="Pre-audit advisories or disclosure reminders")
    audit_completed: bool = Field(default=False, description="Always False upon generation; true only after AI Audit Engine runs")
    human_approved: bool = Field(default=False, description="Always False upon generation; requires authorized human review")

    model_config = ConfigDict(extra="ignore")


class BrandContextSummary(BaseModel):
    """Authoritative context retrieved from the shared intelligence foundation."""
    applicable_rule_names: List[str] = Field(default_factory=list)
    verified_claim_keys: List[str] = Field(default_factory=list)
    required_disclosures: List[str] = Field(default_factory=list)
    unverified_requested_claims: List[str] = Field(default_factory=list)
    jurisdiction: str = "Global"
    knowledge_available: bool = True
    limited_mode: bool = False
    limited_mode_reason: Optional[str] = None


class MarketingGenerationResponse(BaseModel):
    """Unified response from the Marketing Copilot service."""
    generation_id: str
    created_at: datetime = Field(default_factory=lambda: datetime.now(timezone.utc))
    brief: CampaignBriefRequest
    alternatives: List[MarketingAlternative]
    brand_context: BrandContextSummary
    model_version: str = "inkloom-marketing-copilot-v1"
    prompt_version: str = "2026.3.0"
    notice: str = (
        "AI-generated creative drafts must be audited via the AI Audit Engine and approved by an authorized "
        "human reviewer prior to public distribution."
    )


class SaveDraftRequest(BaseModel):
    """Request to persist an alternative or customized copy as an organizational draft."""
    title: str = Field(..., min_length=1, max_length=200)
    text: str = Field(..., min_length=1)
    content_type: str = Field(default="text")
    channel: Optional[str] = None
    target_audience: Optional[str] = None
    campaign_objective: Optional[str] = None
    generation_id: Optional[str] = None
    alternative_id: Optional[str] = None
    media_metadata: Optional[Dict[str, Any]] = None


class UpdateDraftRevisionRequest(BaseModel):
    """Request to record an edited revision for an existing draft."""
    text: str = Field(..., min_length=1)
    change_summary: Optional[str] = Field(None, description="Summary of adjustments made by employee")
    media_metadata: Optional[Dict[str, Any]] = None


class DraftDetailResponse(BaseModel):
    """Full draft details including version history and audit status."""
    id: str
    organization_id: str
    creator_id: Optional[str] = None
    title: str
    description: Optional[str] = None
    content_type: str
    status: str
    current_revision_id: Optional[str] = None
    current_text: Optional[str] = None
    version_number: int = 1
    created_at: datetime
    updated_at: datetime
    revisions: List[Dict[str, Any]] = Field(default_factory=list)
    latest_audit: Optional[Dict[str, Any]] = None

    model_config = ConfigDict(from_attributes=True)
