class ReferenceImageAnalysisRequest(BaseModel):
    """Request for genuine visual reference-image or revision inspection."""
    file_path: Optional[str] = Field(None, description="Local path to uploaded image file")
    submission_id: Optional[str] = Field(None, description="Active submission ID containing design file")
    revision_id: Optional[str] = Field(None, description="Exact revision version ID to analyze")
    user_query: Optional[str] = Field(None, description="Specific designer inquiry or focus area")
    image_base64: Optional[str] = Field(None, description="Base64 encoded image data for direct client-side analysis")


class ReferenceImageAnalysisResponse(BaseModel):
    """Structured response from visual image inspection grounded in PIL metrics."""
    file_name: str
    dimensions: Dict[str, Any] = Field(default_factory=dict)
    dominant_colors_hex: List[str] = Field(default_factory=list)
    contrast_ratio: Optional[float] = None
    wcag_aa_compliant: Optional[bool] = None
    brand_palette_concordance: str = "evaluated"
    visual_hierarchy_critique: str
    observable_facts: List[str] = Field(default_factory=list)
    actionable_recommendations: List[str] = Field(default_factory=list)
    color_recommendations: List[str] = Field(default_factory=list)
    typography_recommendations: List[str] = Field(default_factory=list)
    uncertainty_limitations: List[str] = Field(default_factory=list)
    analysis_timestamp: datetime = Field(default_factory=lambda: datetime.now(timezone.utc))


class DesignCritiqueIssue(BaseModel):
    """Detailed critique finding providing cause, impact, fix, and alternative."""
    issue: str
    why_it_matters: str
    how_to_fix: str
    suggested_alternative: str
    uncertainty_or_limitation: Optional[str] = None


class DesignCritiqueRequest(BaseModel):
    """Request for structured design critique."""
    concept_id: Optional[str] = None
    concept_data: Optional[Dict[str, Any]] = None
    submission_id: Optional[str] = None
    channel: Optional[DesignPlacementChannel] = None
    focus_areas: List[str] = Field(default_factory=lambda: ["hierarchy", "contrast", "composition", "branding"])


class DesignCritiqueResponse(BaseModel):
    """Structured, actionable design critique output."""
    critique_id: str = Field(default_factory=lambda: str(uuid.uuid4()))
    overall_summary: str
    strengths: List[str] = Field(default_factory=list)
    critical_issues: List[DesignCritiqueIssue] = Field(default_factory=list)
    hierarchy_score: float = Field(default=85.0, ge=0.0, le=100.0)
    accessibility_score: float = Field(default=90.0, ge=0.0, le=100.0)
    brand_consistency_score: float = Field(default=90.0, ge=0.0, le=100.0)
    actionable_next_steps: List[str] = Field(default_factory=list)


class DesignAdaptationRequest(BaseModel):
    """Request to iteratively adapt a design concept (e.g. 'make it more premium', change channel)."""
    base_concept: Dict[str, Any]
    adaptation_instruction: str = Field(..., description="E.g. 'make it more premium', 'adapt for Instagram'")
    target_channel: Optional[DesignPlacementChannel] = None
    target_aspect_ratio: Optional[DesignAspectRatio] = None
    preserve_elements: List[str] = Field(default_factory=lambda: ["headline", "product", "logo_placement"])


class DesignAdaptationResponse(BaseModel):
    """Structured response detailing iterative adaptation results."""
    adaptation_id: str = Field(default_factory=lambda: str(uuid.uuid4()))
    adapted_concept: DesignConceptAlternative
    applied_modifications: List[str] = Field(default_factory=list)
    preserved_elements: List[str] = Field(default_factory=list)
    design_rationale: str

