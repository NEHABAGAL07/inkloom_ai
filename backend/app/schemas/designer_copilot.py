"""
Designer Copilot Schemas
Pydantic contracts for creative briefs, visual concept generation,
brand asset integration, design versioning, and visual audits.
"""
import uuid
from datetime import datetime, timezone
from enum import Enum
from typing import List, Optional, Dict, Any
from pydantic import BaseModel, Field, ConfigDict


class CreativeFormat(str, Enum):
    SOCIAL_POST = "social_post"
    BANNER = "banner"
    POSTER = "poster"
    AD = "ad"
    LANDING_PAGE_VISUAL = "landing_page_visual"
    PRESENTATION = "presentation"
    INFOGRAPHIC = "infographic"
    EMAIL_HEADER = "email_header"
    COLLATERAL = "collateral"


class DesignPlacementChannel(str, Enum):
    INSTAGRAM = "instagram"
    LINKEDIN = "linkedin"
    WEBSITE = "website"
    EMAIL = "email"
    AD = "ad"
    PRINT = "print"
    PRESENTATION = "presentation"
    GENERAL = "general"


class DesignAspectRatio(str, Enum):
    SQUARE_1_1 = "1:1"
    LANDSCAPE_16_9 = "16:9"
    PORTRAIT_9_16 = "9:16"
    SOCIAL_PORTRAIT_4_5 = "4:5"
    LINKEDIN_1_91_1 = "1.91:1"
    BANNER_728_90 = "728:90"
    RECTANGLE_300_250 = "300:250"
    CUSTOM = "custom"


class AssetApprovalStatus(str, Enum):
    APPROVED = "approved"
    RESTRICTED = "restricted"
    EXPIRED = "expired"
    PENDING_REVIEW = "pending_review"


class BrandAssetItem(BaseModel):
    """Authorized brand asset representation for Designer Copilot."""
    id: str
    organization_id: str
    name: str
    asset_type: str  # logo, color_palette, typography, image, template, illustration
    file_url: Optional[str] = None
    file_path: Optional[str] = None
    specifications: Dict[str, Any] = Field(default_factory=dict)
    approval_status: AssetApprovalStatus = AssetApprovalStatus.APPROVED
    is_active: bool = True

    model_config = ConfigDict(from_attributes=True)


class CreativeBriefRequest(BaseModel):
    """
    Structured creative design brief.
    Allows partial input and incomplete drafts with clear validation.
    """
    project_name: Optional[str] = Field(None, description="Project or campaign name")
    product: Optional[str] = Field(None, description="Product or service name")
    design_objective: Optional[str] = Field(None, description="Primary visual goal, e.g. Awareness, Conversion, Product Education")
    target_audience: Optional[str] = Field(None, description="Target demographic, persona, or professional segment")
    channel: DesignPlacementChannel = Field(default=DesignPlacementChannel.LINKEDIN, description="Placement channel")
    creative_format: CreativeFormat = Field(default=CreativeFormat.SOCIAL_POST, description="Design format")
    visual_style_tone: Optional[str] = Field(None, description="Desired visual style (e.g. Minimalist Tech, Editorial Bold, Vibrant)")
    brand_requirements: Optional[str] = Field(None, description="Mandatory brand elements or safe-area requirements")
    required_copy: Optional[str] = Field(None, description="Mandatory headline, body text, or disclaimer copy")
    call_to_action: Optional[str] = Field(None, description="CTA label and button direction")
    aspect_ratio: DesignAspectRatio = Field(default=DesignAspectRatio.SQUARE_1_1, description="Target aspect ratio")
    custom_dimensions: Optional[str] = Field(None, description="Explicit dimensions (e.g. '1200x630') if custom")
    selected_asset_ids: List[str] = Field(default_factory=list, description="IDs of authorized brand assets to incorporate")
    reference_notes: Optional[str] = Field(None, description="User-supplied references, design benchmarks, or constraints")
    num_concepts: int = Field(default=3, ge=1, le=4, description="Number of visual concepts to generate")

    model_config = ConfigDict(extra="ignore")


class ColorTokenRecommendation(BaseModel):
    name: str
    hex: str
    role: str  # primary, accent, background, text, neutral
    usage_guidance: str
    contrast_ratio_notes: Optional[str] = None


class TypographyRecommendation(BaseModel):
    font_family: str
    weight: str
    role: str  # headline, subhead, body, caption
    size_guidance: str


class DesignConceptAlternative(BaseModel):
    """
    Structured visual design concept generated by Designer Copilot.
    Clearly marks AI-generated and unapproved status.
    """
    id: str = Field(description="Unique identifier for the design concept")
    concept_name: str = Field(description="Title of this creative visual direction")
    creative_objective_rationale: str = Field(description="Why this concept solves the design brief")
    visual_direction_composition: str = Field(description="Visual balance, focal point, and art direction")
    suggested_layout_hierarchy: str = Field(description="Information flow and spatial structure")
    color_palette_tokens: List[ColorTokenRecommendation] = Field(default_factory=list)
    typography_recommendations: List[TypographyRecommendation] = Field(default_factory=list)
    imagery_illustration_direction: str = Field(description="Style of photos, 3D renders, or illustrations to use")
    logo_asset_placement: str = Field(description="Placement, size, and clear-space buffer for brand logo")
    headline_copy_suggestion: str = Field(description="Grounded headline for visual display")
    supporting_copy_suggestion: Optional[str] = Field(None, description="Subhead or supporting copy")
    call_to_action_placement: str = Field(description="Button placement, contrast, and visual prominence")
    channel_specific_considerations: str = Field(description="Platform nuances, mobile viewport, safe zones")
    accessibility_considerations: str = Field(description="WCAG 2.1 AA contrast, alt text, and minimum text sizes")
    relevant_brand_rules: List[str] = Field(default_factory=list, description="Brand rules adhered to")
    assumptions: List[str] = Field(default_factory=list, description="Assumptions made in absence of complete specs")
    missing_information: List[str] = Field(default_factory=list, description="Missing brand assets or unverified facts")
    warnings: List[str] = Field(default_factory=list, description="Advisories regarding unverified claims or sizing")
    is_ai_generated: bool = Field(default=True, description="Always True for generated concepts")
    is_approved: bool = Field(default=False, description="Always False upon generation; requires authorized human review")
    audit_completed: bool = Field(default=False, description="Always False upon concept generation")

    model_config = ConfigDict(extra="ignore")


class DesignConceptGenerationResponse(BaseModel):
    """Response containing multiple distinct design concepts."""
    generation_id: str
    created_at: datetime = Field(default_factory=lambda: datetime.now(timezone.utc))
    brief: CreativeBriefRequest
    concepts: List[DesignConceptAlternative]
    brand_assets_used: List[BrandAssetItem] = Field(default_factory=list)
    brand_rules_applied: List[str] = Field(default_factory=list)
    model_version: str = "inkloom-designer-copilot-v1"
    notice: str = (
        "Design concepts are AI-generated proposals. Designs must be rendered/uploaded and audited "
        "prior to authorized human review and final approval."
    )


class SaveCreativeBriefDraftRequest(BaseModel):
    """Request to persist a creative brief and optional selected concept."""
    project_name: str = Field(..., min_length=1, max_length=200)
    brief: CreativeBriefRequest
    selected_concept_id: Optional[str] = None
    selected_concept_data: Optional[Dict[str, Any]] = None
    initial_image_url: Optional[str] = None


class DesignRevisionItem(BaseModel):
    id: str
    version_number: int
    file_name: Optional[str] = None
    file_path: Optional[str] = None
    raw_text: Optional[str] = None
    created_at: Optional[str] = None
    media_metadata: Dict[str, Any] = Field(default_factory=dict)


class DesignDraftDetailResponse(BaseModel):
    """Detailed response for a design brief, version history, and audit status."""
    id: str
    organization_id: str
    creator_id: Optional[str] = None
    title: str
    description: Optional[str] = None
    content_type: str = "image"
    status: str
    current_revision_id: Optional[str] = None
    current_file_path: Optional[str] = None
    current_file_name: Optional[str] = None
    version_number: int = 1
    brief: Optional[Dict[str, Any]] = None
    selected_concept: Optional[Dict[str, Any]] = None
    created_at: datetime
    updated_at: datetime
    revisions: List[DesignRevisionItem] = Field(default_factory=list)
    latest_audit: Optional[Dict[str, Any]] = None

    model_config = ConfigDict(from_attributes=True)


